create table if not exists public.waitlist_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  login text not null unique
    check (login = lower(login) and login ~ '^[a-z0-9_.-]{3,24}$'),
  who text not null check (char_length(who) between 3 and 1200),
  from_where text not null check (char_length(from_where) between 3 and 1200),
  why_server text not null check (char_length(why_server) between 3 and 1200),
  why_you text not null check (char_length(why_you) between 3 and 1200),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create index if not exists waitlist_applications_status_created_idx
  on public.waitlist_applications (status, created_at desc);

alter table public.waitlist_applications enable row level security;

revoke all on table public.waitlist_applications from anon;
revoke insert, update, delete on table public.waitlist_applications from authenticated;
grant select on table public.waitlist_applications to authenticated;

drop policy if exists "Applicants can read their own application"
  on public.waitlist_applications;

create policy "Applicants can read their own application"
  on public.waitlist_applications
  for select
  to authenticated
  using ((select auth.uid()) = user_id);
