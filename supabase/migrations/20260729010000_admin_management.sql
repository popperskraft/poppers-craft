create table if not exists public.application_votes (
  application_id bigint not null
    references public.waitlist_applications(id) on delete cascade,
  admin_id bigint not null
    references public.admin_profiles(id) on delete restrict,
  vote text not null check (vote in ('approve', 'reject')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (application_id, admin_id)
);

create index if not exists application_votes_application_idx
  on public.application_votes (application_id, vote);

create table if not exists public.moderation_proposals (
  id bigint generated by default as identity primary key,
  application_id bigint not null
    references public.waitlist_applications(id) on delete cascade,
  action text not null check (action in ('ban', 'delete')),
  reason text not null check (char_length(reason) between 3 and 500),
  status text not null default 'pending'
    check (status in ('pending', 'executed', 'rejected')),
  created_by bigint not null
    references public.admin_profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create unique index if not exists one_pending_moderation_action
  on public.moderation_proposals (application_id, action)
  where status = 'pending';

create table if not exists public.moderation_votes (
  proposal_id bigint not null
    references public.moderation_proposals(id) on delete cascade,
  admin_id bigint not null
    references public.admin_profiles(id) on delete restrict,
  vote text not null check (vote in ('approve', 'reject')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (proposal_id, admin_id)
);

create index if not exists moderation_votes_proposal_idx
  on public.moderation_votes (proposal_id, vote);

create table if not exists public.site_updates (
  id bigint generated by default as identity primary key,
  source_key text unique,
  badge text not null check (char_length(badge) between 2 and 16),
  title text not null check (char_length(title) between 3 and 120),
  body text not null check (char_length(body) between 3 and 1200),
  color text not null default 'lime'
    check (color in ('lime', 'pink', 'cyan', 'yellow')),
  published boolean not null default true,
  author_admin_id bigint references public.admin_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

