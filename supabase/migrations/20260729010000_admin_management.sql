alter table public.waitlist_applications
  alter column user_id drop not null;

alter table public.waitlist_applications
  drop constraint if exists waitlist_applications_user_id_fkey;

alter table public.waitlist_applications
  add constraint waitlist_applications_user_id_fkey
  foreign key (user_id) references auth.users(id) on delete set null;

alter table public.waitlist_applications
  add column if not exists is_banned boolean not null default false,
  add column if not exists ban_reason text,
  add column if not exists banned_at timestamptz,
  add column if not exists is_deleted boolean not null default false,
  add column if not exists deleted_at timestamptz;

create table if not exists public.admin_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  email text not null unique
    check (email = lower(email) and position('@' in email) > 1),
  display_name text not null check (char_length(display_name) between 2 and 80),
  role text not null default 'admin'
    check (role in ('owner', 'admin')),
  active boolean not null default true,
  created_by bigint references public.admin_profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

