create table if not exists public.pc_member_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  login text not null unique check (login = lower(login) and login ~ '^[a-z0-9_.-]{3,40}$'),
  display_name text not null check (char_length(display_name) between 2 and 80),
  bio text not null default '' check (char_length(bio) <= 1200),
  favorite_music text not null default '' check (char_length(favorite_music) <= 500),
  favorite_movies text not null default '' check (char_length(favorite_movies) <= 500),
  social_links text not null default '' check (char_length(social_links) <= 1000),
  header_color text not null default '#1c44da' check (header_color ~ '^#[0-9A-Fa-f]{6}$'),
  header_flag text not null default 'none' check (header_flag in ('none', 'rainbow', 'transgender', 'usa')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pc_feed_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.pc_member_profiles(user_id) on delete cascade,
  title text not null check (char_length(title) between 3 and 120),
  body text not null check (char_length(body) between 1 and 5000),
  image_path text check (image_path is null or char_length(image_path) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pc_feed_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.pc_feed_posts(id) on delete cascade,
  author_id uuid not null references public.pc_member_profiles(user_id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);

create table if not exists public.pc_feed_reactions (
  post_id bigint not null references public.pc_feed_posts(id) on delete cascade,
  user_id uuid not null references public.pc_member_profiles(user_id) on delete cascade,
  reaction text not null check (reaction in ('like', 'dislike')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table if not exists public.pc_profile_follows (
  follower_id uuid not null references public.pc_member_profiles(user_id) on delete cascade,
  following_id uuid not null references public.pc_member_profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, following_id),
  check (follower_id <> following_id)
);

create index if not exists pc_feed_posts_author_created_idx
  on public.pc_feed_posts (author_id, created_at desc);
create index if not exists pc_feed_posts_created_idx
  on public.pc_feed_posts (created_at desc);
create index if not exists pc_feed_comments_post_created_idx
  on public.pc_feed_comments (post_id, created_at);
create index if not exists pc_feed_reactions_post_reaction_idx
  on public.pc_feed_reactions (post_id, reaction);
create index if not exists pc_profile_follows_following_idx
  on public.pc_profile_follows (following_id, follower_id);

insert into public.pc_member_profiles
  (user_id, login, display_name, bio, favorite_music, social_links)
select
  application.user_id,
  lower(application.login),
  left(coalesce(nullif(application.who, ''), application.login), 80),
  left(coalesce(application.who, ''), 1200),
  left(coalesce(auth_user.raw_user_meta_data ->> 'favorite_music', ''), 500),
  left(coalesce(auth_user.raw_user_meta_data ->> 'social_links', ''), 1000)
from public.waitlist_applications application
join auth.users auth_user on auth_user.id = application.user_id
where application.user_id is not null
  and application.status = 'approved'
  and not coalesce(application.is_deleted, false)
  and not coalesce(application.is_banned, false)
on conflict (user_id) do update set
  login = excluded.login,
  display_name = excluded.display_name,
  bio = case when public.pc_member_profiles.bio = '' then excluded.bio else public.pc_member_profiles.bio end,
  favorite_music = case when public.pc_member_profiles.favorite_music = '' then excluded.favorite_music else public.pc_member_profiles.favorite_music end,
  social_links = case when public.pc_member_profiles.social_links = '' then excluded.social_links else public.pc_member_profiles.social_links end;

insert into public.pc_member_profiles (user_id, login, display_name, bio)
select
  admin.user_id,
  lower(regexp_replace(split_part(admin.email, '@', 1), '[^a-zA-Z0-9_.-]', '', 'g')),
  left(admin.display_name, 80),
  'Администратор PoppersCraft'
from public.admin_profiles admin
where admin.user_id is not null and admin.active
on conflict (user_id) do update set
  display_name = excluded.display_name;

