export async function generatePoppersAnswer(question: string, extraContext = "") {
  /* Готовые ответы написаны по-русски — на английский вопрос отвечает модель. */
  const directAnswer = isEnglishQuestion(question) ? null : poppersDirectAnswer(question);
  if (directAnswer) return { answer: directAnswer, needsHuman: false };
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) throw new Error("gemini-key-missing");
  const primaryModel = process.env.GEMINI_MODEL?.trim() || "gemini-3.6-flash";
  const fallbackModel = process.env.GEMINI_FALLBACK_MODEL?.trim() || "gemini-2.5-flash";
  const [databaseText, teamAnswers, liveFacts] = await Promise.all([publishedKnowledge(), approvedKnowledgeFor(question), paymentFacts()]);
  const prompt = poppersPrompt(question, databaseText, extraContext, teamAnswers, liveFacts);
  const contents: Array<{ role: "user" | "model"; parts: Array<{ text: string }> }> = [{ role: "user", parts: [{ text: prompt }] }];
  let model = primaryModel;
  let raw = "";
  for (let attempt = 0; attempt < 3; attempt += 1) {
    let reply: { part: string; finishReason?: string };
    try {
      reply = await callGemini(apiKey, model, contents, prompt.length);
    } catch (error) {
      if (model === fallbackModel || fallbackModel === primaryModel) throw error;
      model = fallbackModel;
      reply = await callGemini(apiKey, model, contents, prompt.length);
    }
    const part = reply.part;
    raw = `${raw}${raw ? "\n" : ""}${part}`.trim();
    if (reply.finishReason !== "MAX_TOKENS") break;
    contents.push(
      { role: "model", parts: [{ text: part }] },
      { role: "user", parts: [{ text: "Продолжи ответ ровно с места остановки. Не повторяй уже написанное и обязательно закончи мысль." }] },
    );
  }
  const needsHuman = raw.includes("[NEEDS_HUMAN]");
  const answer = raw.replace(/\s*\[NEEDS_HUMAN]\s*/g, "").trim();
  return { answer, needsHuman };
}
