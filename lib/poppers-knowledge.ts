export async function publishedKnowledge() {
  try {
    const updates = await listSiteUpdates(true);
    return updates
      .slice(0, 20)
      .map((update) => `${update.title}: ${update.board ? update.board.blocks.map((block) => block.text).filter(Boolean).join("; ") : update.body}`)
      .join("\n")
      .slice(0, 12_000);
  } catch {
    return "База обновлений временно недоступна.";
  }
}

