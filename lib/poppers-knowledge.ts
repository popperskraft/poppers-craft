/* Временные ошибки Gemini (перегрузка 503, лимиты 429, сбои 5xx) повторяем с паузой,
   а если основная модель так и не ответила — спрашиваем запасную. */
const TRANSIENT_STATUSES = new Set([429, 500, 502, 503, 504]);

async function callGemini(apiKey: string, model: string, contents: unknown, promptLength: number) {
  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent`;
  let lastError = "gemini-empty-answer";
  for (let attempt = 0; attempt < 3; attempt += 1) {
    if (attempt > 0) await new Promise((resolve) => setTimeout(resolve, attempt === 1 ? 1_000 : 2_500));
    try {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json", "x-goog-api-key": apiKey },
        body: JSON.stringify({ contents, generationConfig: { temperature: 0.2, maxOutputTokens: 1_400 } }),
        signal: AbortSignal.timeout(25_000),
      });
      const result = await response.json().catch(() => null);
      const candidate = result?.candidates?.[0];
      const part = candidate?.content?.parts?.map((item: { text?: string }) => item.text ?? "").join("").trim();
      if (response.ok && part) return { part: part as string, finishReason: candidate?.finishReason as string | undefined };
      console.error("Gemini failed", { status: response.status, model, promptLength, attempt, error: result?.error?.message ?? "empty-answer" });
      lastError = `gemini-${response.status}`;
      if (!TRANSIENT_STATUSES.has(response.status)) break;
    } catch (error) {
      console.error("Gemini request failed", { model, attempt, error: error instanceof Error ? error.message : "unknown" });
      lastError = "gemini-network";
    }
  }
  throw new Error(lastError);
}

